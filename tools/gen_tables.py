#!/usr/bin/env python3
"""ABYSS DSP tables.   gen_tables.py OUT.h"""
import math
import sys

FS = 24_000_000 / 544          # the FM-1's I2S frame rate: 44117.6 Hz


def main(out):
    L = ["/* generated by tools/gen_tables.py: do not edit */", "#pragma once", "#include <stdint.h>",
         f"#define AB_FS {round(FS)}u", f"#define AB_FS_F {FS:.4f}"]
    # sine, Q15, 1024 points + guard
    s = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
    L.append("static const int16_t AB_SINE[1025] = {" + ",".join(map(str, s)) + "};")
    # phase increment of the top octave (MIDI 120 .. 131.98) in 1/64 semitone; lower octaves shift right
    inc = []
    for i in range(768):
        note = 120 + i / 64
        f = 440 * 2 ** ((note - 69) / 12)
        inc.append(min(0xFFFFFFFF, round(f / FS * 2 ** 32)))
    L.append("#define AB_PITCH_TOP (120 * 64)")
    L.append("static const uint32_t AB_OCT_INC[768] = {" + ",".join(f"{v}u" for v in inc) + "};")
    # SVF coefficient (Q14) of the cutoff knob 0..128, the filter run twice a sample (2 x FS)
    cf = []
    for k in range(129):
        fc = 20 * (18000 / 20) ** (min(k, 127) / 127)
        f = 2 * math.sin(math.pi * min(fc, 0.2 * 2 * FS) / (2 * 2 * FS))
        cf.append(round(f * 16384))
    L.append("static const uint16_t AB_CUT_F[129] = {" + ",".join(map(str, cf)) + "};")
    # cutoff in Hz x 10 for the display
    hz = [round(20 * (18000 / 20) ** (min(k, 127) / 127) * 10) for k in range(129)]
    L.append("static const uint32_t AB_CUT_HZ10[129] = {" + ",".join(f"{v}u" for v in hz) + "};")
    # envelope: time knob 0..127 -> per-block (32 samples) Q24 step; 1 ms .. 10 s
    st = []
    for k in range(128):
        t = 0.001 * (10000 ** (k / 127))
        blocks = max(1.0, t * FS / 32)
        st.append(max(1, round((1 << 24) / blocks)))
    L.append("static const uint32_t AB_ENV_STEP[128] = {" + ",".join(f"{v}u" for v in st) + "};")
    ek = []                       # exponential segments: per-block coefficient, Q16, ~-60 dB at the time
    for k in range(128):
        t = 0.001 * (10000 ** (k / 127))
        blocks = max(1.0, t * FS / 32)
        ek.append(max(1, min(65535, round(65536 * (1 - math.exp(-6.9 / blocks))))))
    L.append("static const uint16_t AB_ENV_K[128] = {" + ",".join(map(str, ek)) + "};")
    # LFO / random rate knob 0..127: 0.02 Hz .. 40 Hz; phase increment per block of 32 samples; Hz x 100
    lhz = [0.02 * 2000 ** (k / 127) for k in range(128)]
    L.append("static const uint32_t AB_LFO_INC[128] = {" +
             ",".join(f"{round(h * 32 / FS * 2 ** 32)}u" for h in lhz) + "};")
    L.append("static const uint32_t AB_LFO_HZ100[128] = {" + ",".join(f"{round(h * 100)}u" for h in lhz) + "};")
    # DRIVE 0..100 -> gain Q8, 1 .. ~47
    L.append("static const uint16_t AB_DRIVE_G[101] = {" + ",".join(str(round(256 * 2 ** (d / 18))) for d in range(101)) + "};")
    # TONE 0..100 -> one-pole low-pass coefficient Q15, 400 Hz .. 18 kHz (100 = open)
    tk = []
    for t in range(101):
        fc = 400 * (18000 / 400) ** (t / 100)
        tk.append(min(32767, round(32768 * (1 - math.exp(-2 * math.pi * fc / FS)))))
    L.append("static const uint16_t AB_TONE_K[101] = {" + ",".join(map(str, tk)) + "};")
    # delay TIME 0..127 -> 20 ms .. 1400 ms; in half-rate samples Q16 (the lines run at FS / 2) and in ms x 10
    dt = [0.020 * (1.400 / 0.020) ** (k / 127) for k in range(128)]
    L.append("static const uint32_t AB_DTIME_Q16[128] = {" + ",".join(f"{round(t * FS / 2 * 65536)}u" for t in dt) + "};")
    L.append("static const uint32_t AB_DTIME_MS10[128] = {" + ",".join(f"{round(t * 10000)}u" for t in dt) + "};")
    ms = [round(1000 * 0.001 * (10000 ** (k / 127)) * 10) for k in range(128)]
    L.append("static const uint32_t AB_ENV_MS10[128] = {" + ",".join(f"{v}u" for v in ms) + "};")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"tables -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
