#!/usr/bin/env python3
"""ABYSS: rasterise Inter Tight (OFL) into 4-bit anti-aliased glyph tables for the 240x240 LCD.

    gen_fonts.py OUT.h

Each face: printable ASCII 32..126, 4 bits of coverage per pixel (two pixels a byte, rows padded to a byte).
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "assets" / "fonts" / "InterTight.ttf"

# name, pixel size, weight, extra tracking (px), characters
FACES = [
    ("F_LABEL", 12, 560, 1, None),     # small caps labels, page tag
    ("F_TITLE", 21, 700, 0, None),     # "ABYSS"
    ("F_MID", 24, 600, 0, None),       # secondary values
    ("F_VAL", 19, 600, 0, None),       # four small values in a row (OSC pages)
    ("F_BIG", 44, 600, 0, None),       # the primary value
    ("F_HUGE", 76, 600, -1, "0123456789.-+%: "),   # performance mode digits
]


def face(name, size, weight, track, chars):
    f = ImageFont.truetype(str(TTF), size)
    f.set_variation_by_axes([weight])
    asc, desc = f.getmetrics()
    first, last = 32, 126
    glyphs, data = [], bytearray()
    for c in range(first, last + 1):
        ch = chr(c)
        if chars is not None and ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = round(f.getlength(ch)) + track
        bbox = f.getbbox(ch)          # relative to the origin at the top of the ascent
        if ch == " " or bbox[2] <= bbox[0]:
            glyphs.append((0, 0, 0, 0, adv, len(data)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255)
        off = len(data)
        px = im.load()
        for y in range(h):
            row = [min(15, (px[x, y] + 8) // 17) for x in range(w)]
            if len(row) % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append(row[i] << 4 | row[i + 1])
        glyphs.append((w, h, x0, y0, adv, off))
    return asc, desc, glyphs, data


def main(out):
    lines = ["/* generated by tools/gen_fonts.py from Inter Tight (SIL OFL 1.1): do not edit */",
             "#pragma once", "#include <stdint.h>",
             "typedef struct { uint8_t w, h; int8_t x, y; uint8_t adv; uint8_t pad; uint16_t hi; uint16_t off; } ab_glyph_t;",
             "typedef struct { uint8_t size, asc, desc, cap; const ab_glyph_t *g; const uint8_t *d; } ab_font_t;"]
    total = 0
    for name, size, weight, track, chars in FACES:
        asc, desc, glyphs, data = face(name, size, weight, track, chars)
        cap = glyphs[ord("0") - 32][1]
        lines.append(f"static const uint8_t {name}_D[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const ab_glyph_t {name}_G[95] = {{")
        for (w, h, x, y, adv, off) in glyphs:
            lines.append(f"    {{{w},{h},{x},{y},{adv},0,{off >> 16},{off & 0xFFFF}}},")
        lines.append("};")
        lines.append(f"static const ab_font_t {name} = {{{size},{asc},{desc},{cap},{name}_G,{name}_D}};")
        total += len(data) + 95 * 10
        print(f"{name}: {size}px w{weight}  {len(data)} B")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"fonts: {total} B -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
